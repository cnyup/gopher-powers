package pathfind

import "testing"

// 黄金向量 tick1085：scout#29 重寻路现场（双侧网格 dump 逐格一致后 JS 库实测输出）。
// raw:       [[48,13][47,13][46,13][45,13][44,13][43,14][42,15][41,15][40,15][39,16][38,17][37,17][36,17][35,17][34,18][33,18][32,18][31,18][30,18][29,19][28,20][27,21]]
// compressed: [[48,13][44,13][42,15][40,15][38,17][35,17][34,18][30,18][27,21]]
func TestGoldenTick1085(t *testing.T) {
	grid := NewGrid(56, 36)
	blocked := [][2]int{
		{46, 11}, {47, 11}, {47, 12}, {50, 13}, {51, 13}, {47, 14}, {50, 14},
		{51, 14}, {47, 15}, {48, 15}, {44, 17}, {50, 17}, {51, 17}, {43, 18},
		{44, 18}, {45, 18}, {50, 18}, {51, 18}, {44, 19}, {47, 20}, {48, 20},
		{43, 21}, {47, 21}, {48, 21}, {42, 22}, {43, 22},
	}
	for _, b := range blocked {
		grid.SetWalkableAt(b[0], b[1], false)
	}
	raw := FindPath(48, 13, 27, 21, grid)
	wantRaw := []Node{
		{48, 13}, {47, 13}, {46, 13}, {45, 13}, {44, 13}, {43, 14}, {42, 15},
		{41, 15}, {40, 15}, {39, 16}, {38, 16}, {37, 17}, {36, 17}, {35, 17},
		{34, 18}, {33, 18}, {32, 18}, {31, 18}, {30, 18}, {29, 19}, {28, 20}, {27, 21},
	}
	if len(raw) != len(wantRaw) {
		t.Fatalf("raw len = %d, want %d:\n got %v\nwant %v", len(raw), len(wantRaw), raw, wantRaw)
	}
	for i, n := range raw {
		if n != wantRaw[i] {
			t.Fatalf("raw[%d] = %v, want %v\n got %v\nwant %v", i, n, wantRaw[i], raw, wantRaw)
		}
	}
}
